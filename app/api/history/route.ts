import { NextResponse } from "next/server";
import { getSql } from "@/lib/db/client";

export async function GET() {
  try {
    const db = getSql();
    const rows = await db`SELECT id, a_label, b_label, c_label, confidence, threshold, outcome, label, created_at FROM arbitro.verdicts ORDER BY id DESC LIMIT 20`;
    return NextResponse.json({ verdicts: rows });
  } catch (err) {
    return NextResponse.json(
      { error: err instanceof Error ? err.message : "Error leyendo historial" },
      { status: 500 },
    );
  }
}
